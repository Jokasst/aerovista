function translateDateString(str, lang) {
  if (lang === 'en') return str;
  return str.replace(/\b([A-Z][a-z]{2})\b/g, (m) => {
    const idx = monthNamesAbbr.en.indexOf(m);
    return idx > -1 ? monthNamesAbbr.ru[idx] : m;
  });
}

