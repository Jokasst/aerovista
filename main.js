function showBanner(bannerEl, message, modifierClass) {
  if (!bannerEl) return;
  bannerEl.textContent = message;
  bannerEl.classList.add(modifierClass);
}

function hideBanner(bannerEl, modifierClass) {
  if (!bannerEl) return;
  bannerEl.classList.remove(modifierClass);
}

